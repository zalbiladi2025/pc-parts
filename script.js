/* ---------------------------------------------------------
   بناء المخطط التشريحي (Hotspots) وشريط التنقل
   --------------------------------------------------------- */
const hotspotBoard = document.getElementById("hotspotBoard");
const pillNav = document.getElementById("pillNav");
const sectionsWrap = document.getElementById("sections");
const cheatGrid = document.getElementById("cheatGrid");

components.forEach(c => {
  // Hotspot في البطل
  const hs = document.createElement("a");
  hs.href = `#${c.id}`;
  hs.className = "hotspot";
  hs.innerHTML = `
    <span class="hotspot-icon">${c.icon}</span>
    <span class="hotspot-num mono">${c.num}</span>
    <span class="hotspot-name">${c.name}</span>
  `;
  hotspotBoard.appendChild(hs);

  // رابط في شريط التنقل
  const navLink = document.createElement("a");
  navLink.href = `#${c.id}`;
  navLink.dataset.target = c.id;
  navLink.textContent = c.name;
  pillNav.appendChild(navLink);

  // قسم الشرح الكامل
  const section = document.createElement("section");
  section.className = "comp-section";
  section.id = c.id;
  section.innerHTML = `
    <div class="comp-head">
      <div class="comp-icon-badge">${c.icon}</div>
      <div class="comp-titles">
        <span class="comp-num mono">القطعة ${c.num}</span>
        <h2>${c.name} <span class="comp-en">/ ${c.en}</span></h2>
      </div>
    </div>
    <p class="comp-tagline">${c.tagline}</p>
    <p class="comp-desc">${c.desc}</p>
    <div class="spec-grid">
      ${c.specs.map(s => `
        <div class="spec-card">
          <span class="spec-label">${s.label}</span>
          <span class="spec-value">${s.value}</span>
        </div>
      `).join("")}
    </div>
    <div class="info-boxes">
      <div class="info-box fact">
        <div class="info-box-title">✨ هل تعلم؟</div>
        <p>${c.fact}</p>
      </div>
      <div class="info-box tip">
        <div class="info-box-title">🔧 نصيحة توافق</div>
        <p>${c.tip}</p>
      </div>
    </div>
  `;
  sectionsWrap.appendChild(section);
});

cheatSheet.forEach(item => {
  const card = document.createElement("div");
  card.className = "cheat-card";
  card.innerHTML = `
    <span class="cheat-num mono">قاعدة ${item.num}</span>
    <p><strong>${item.title}:</strong> ${item.text}</p>
  `;
  cheatGrid.appendChild(card);
});

/* ---------------------------------------------------------
   تمييز الرابط النشط أثناء التمرير (Scrollspy)
   --------------------------------------------------------- */
const navLinks = pillNav.querySelectorAll("a");
const sectionEls = sectionsWrap.querySelectorAll(".comp-section");

const observer = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting){
      const id = entry.target.id;
      navLinks.forEach(l => l.classList.toggle("active", l.dataset.target === id));
    }
  });
}, { rootMargin: "-40% 0px -50% 0px", threshold: 0 });

sectionEls.forEach(sec => observer.observe(sec));
